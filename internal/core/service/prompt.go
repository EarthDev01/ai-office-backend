const round1Instruction = "เลือกเครื่องมือที่ตรงกับคำถามที่สุด (เรียกหลายตัวพร้อมกันได้ถ้าคำถามมีหลายเรื่อง) · " +
	"ถ้าไม่ต้องใช้ข้อมูลจากระบบ ให้เรียก answer_directly · ถ้าผู้ใช้ขอให้ทำรายการ ให้เรียก answer_directly(category=action_request) " +
	"พร้อม lookup_menu เพื่อหาเส้นทางเมนู · ถ้าถามวิธีทำหรือเมนูอยู่ตรงไหน ให้เรียก lookup_menu"

func itoa(i int) string {
	const digits = "0123456789"
	if i < 10 {
		return string(digits[i])
	}
	return itoa(i/10) + string(digits[i%10])
}
